import { mkdir, mkdtemp, realpath, rename, rm, symlink } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { afterEach, describe, expect, it } from 'vitest';
import { WorkbookStore } from '../store.service.js';
import { assertCheckBackend, assertCheckWorkspace } from '../check-isolation.helper.js';

const roots: string[] = [];

afterEach(async () => {
  await Promise.all(roots.splice(0).map((root) => rm(root, { recursive: true, force: true })));
});

async function fixture() {
  const root = await mkdtemp(path.join(tmpdir(), 'workbook-isolation-'));

  roots.push(root);

  const store = new WorkbookStore(path.join(root, 'workbook'));
  const prepared = await store.workspace({ prompt: undefined, key: 'check', keep: false });
  const params = {
    store,
    name: 'check',
    workspaceRoot: prepared.dir,
    actualWorkspace: prepared.dir,
  };

  return { root, store, prepared, params };
}

describe('check isolation', () => {
  it('rejects external backend selection without mutating the environment', () => {
    const env = {
      BACKEND_URL: 'http://external.test',
      BACKEND_TOKEN: 'fake',
      HOME: '/unchanged',
      SHEAVLY_HOME: '/unchanged-store',
    };
    const before = { ...env };

    expect(() => assertCheckBackend(env)).toThrow(/own backend/);
    expect(env).toEqual(before);
    expect(() => assertCheckBackend({ BACKEND_URL: '' })).not.toThrow();
  });

  it('accepts only the canonical workspace generated by this store', async () => {
    const { root, prepared, params } = await fixture();
    const alias = path.join(root, 'alias');

    await symlink(prepared.dir, alias);
    await expect(
      assertCheckWorkspace({ ...params, actualWorkspace: alias }),
    ).resolves.toBeUndefined();
    await expect(assertCheckWorkspace({ ...params, actualWorkspace: root })).rejects.toThrow(
      /does not match/,
    );
    await expect(assertCheckWorkspace({ ...params, workspaceRoot: root })).rejects.toThrow(
      /does not match/,
    );
    await expect(
      assertCheckWorkspace({ ...params, actualWorkspace: path.join(root, 'missing') }),
    ).rejects.toThrow(/Could not verify/);
  });

  it.each(['workspaces', 'prompt'] as const)(
    'rejects a redirected %s directory even when its backend matches it',
    async (target) => {
      const { root, store, prepared, params } = await fixture();
      const other = path.join(root, 'other');

      if (target === 'workspaces') {
        await rename(store.workspacesDir, other);
        await symlink(other, store.workspacesDir);
      } else {
        await mkdir(other);
        await rm(prepared.dir, { recursive: true });
        await symlink(other, prepared.dir);
      }

      await expect(assertCheckWorkspace(params)).rejects.toThrow(/does not match/);
    },
  );

  it('rejects a generated runs root symlinked outside the store', async () => {
    const { root, store, params } = await fixture();
    const outside = path.join(root, 'outside');

    await mkdir(path.join(outside, 'check'), { recursive: true });
    await rm(path.join(store.workspacesDir, 'runs'), { recursive: true });
    await symlink(outside, path.join(store.workspacesDir, 'runs'));
    expect(await realpath(store.runWorkspaceDir('check'))).toBe(path.join(outside, 'check'));
    await expect(assertCheckWorkspace(params)).rejects.toThrow(/does not match/);
  });
});
