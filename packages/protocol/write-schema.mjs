// Writes the protocol version constant from `package.json`'s `version`, the contract's JSON
// Schema, the API's OpenAPI document and the route table in `docs/contract.md`
// (`npm run schema -w @sheavly/protocol`). Each committed file is checked against the code by
// tests, so rerun this after changing a schema or a route, and after `changeset version`.
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { PROTOCOL_VERSION_FILE } from './src/version/version.constants.ts';

const { version } = JSON.parse(await readFile(join(import.meta.dirname, 'package.json'), 'utf8'));
const versionFile = join(import.meta.dirname, PROTOCOL_VERSION_FILE);
const versionSource = `// Generated by \`npm run schema -w @sheavly/protocol\` from the \`version\` field of package.json: do not edit.
/** The protocol version: this package's version (see "Version" in docs/contract.md). */
export const PROTOCOL_VERSION = ${JSON.stringify(version)};
`;

await writeFile(
  versionFile,
  await format(versionSource, { ...(await resolveConfig(versionFile)), filepath: versionFile }),
);

// Imported only now: these modules read the constant written above.
const { OPENAPI_FILE, ROUTE_TABLE_DOC } = await import('./src/api/api.constants.ts');
const { openApiDocument, withRouteTable } = await import('./src/api/api.utils.ts');
const { CONTRACT_SCHEMA_FILE } = await import('./src/contract/contract.constants.ts');
const { contractJsonSchema } = await import('./src/contract/contract.utils.ts');

for (const [name, document] of [
  [CONTRACT_SCHEMA_FILE, contractJsonSchema()],
  [OPENAPI_FILE, openApiDocument()],
]) {
  const file = join(import.meta.dirname, name);
  const options = await resolveConfig(file);

  await writeFile(file, await format(JSON.stringify(document), { ...options, filepath: file }));
}

const docFile = join(import.meta.dirname, ROUTE_TABLE_DOC);
const withTable = withRouteTable(await readFile(docFile, 'utf8'));

if (withTable === null) throw new TypeError(`${ROUTE_TABLE_DOC} has no route table markers`);

await writeFile(
  docFile,
  await format(withTable, { ...(await resolveConfig(docFile)), filepath: docFile }),
);
