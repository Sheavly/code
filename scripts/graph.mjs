// The workspace graph, drawn from the workspaces themselves (`readLayout`), so the one diagram in
// the docs can't drift from the code. `docs/overview.md` holds it between two markers; the layout
// check (`npm run layout`) fails when it is out of date, and `npm run graph` rewrites it.
//
//   npm run graph   rewrite the diagram in docs/overview.md
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readLayout } from '../packages/eslint-config/src/layout.utils.js';

export const GRAPH_DOC = 'docs/overview.md';
const START = '<!-- graph:start (generated by `npm run graph`; do not edit) -->';
const END = '<!-- graph:end -->';
const SCOPE = '@sheavly/';
const GROUPS = [
  { id: 'generic', title: 'generic packages', match: (entry) => entry.domain === 'generic' },
  {
    id: 'coding',
    title: 'coding packages',
    match: (entry) => entry.kind === 'package' && entry.domain === 'coding',
  },
  { id: 'apps', title: 'apps', match: (entry) => entry.kind === 'app' },
];

const short = (name) => name.slice(SCOPE.length);
const nodeId = (name) => short(name).replaceAll('-', '_');

/** Everything `name` reaches through its runtime dependencies, itself excluded. */
function reachable(params) {
  const { layout, name } = params;
  const seen = new Set();
  const visit = (from) => {
    for (const dep of layout[from]?.dependsOn ?? []) {
      if (!seen.has(dep)) {
        seen.add(dep);
        visit(dep);
      }
    }
  };

  visit(name);

  return seen;
}

/**
 * The edges worth drawing: `a → b` unless `a` already reaches `b` through another dependency
 * (a transitive reduction). What `a` may import is everything it reaches.
 */
export function graphEdges(layout) {
  return Object.entries(layout)
    .flatMap(([name, entry]) =>
      entry.dependsOn
        .filter((dep) =>
          entry.dependsOn.every(
            (other) => other === dep || !reachable({ layout, name: other }).has(dep),
          ),
        )
        .map((dep) => [name, dep]),
    )
    .sort(([a1, b1], [a2, b2]) => a1.localeCompare(a2) || b1.localeCompare(b2));
}

/** The diagram, as a mermaid block between the markers. Tooling and test-only ones are left out. */
export function graphBlock(layout) {
  const shown = Object.fromEntries(
    Object.entries(layout).filter(([, entry]) => entry.domain !== 'tooling' && !entry.testOnly),
  );
  const groups = GROUPS.flatMap(({ id, title, match }) => {
    const names = Object.keys(shown)
      .filter((name) => match(shown[name]))
      .sort();

    return names.length === 0
      ? []
      : [
          `  subgraph group_${id} ["${title}"]`,
          ...names.map((name) => `    ${nodeId(name)}["${name}"]`),
          '  end',
        ];
  });
  const edges = graphEdges(shown).map(([from, to]) => `  ${nodeId(from)} --> ${nodeId(to)}`);

  return [START, '', '```mermaid', 'flowchart BT', ...groups, ...edges, '```', '', END].join('\n');
}

/** `markdown` with its diagram replaced by `block`; null when it has no markers. */
export function withGraph(params) {
  const { markdown, block } = params;
  const start = markdown.indexOf(START);
  const end = markdown.indexOf(END);

  if (start === -1 || end < start) return null;

  return markdown.slice(0, start) + block + markdown.slice(end + END.length);
}

/** Why the diagram in `root`'s overview isn't the graph on disk, or null when it is. */
export function graphProblem(root) {
  const markdown = readFileSync(path.join(root, GRAPH_DOC), 'utf8');
  const updated = withGraph({ markdown, block: graphBlock(readLayout({ root })) });

  if (updated === null) {
    return `${GRAPH_DOC}: the workspace graph markers are missing; put ${START} and ${END} where the diagram goes, then run \`npm run graph\`.`;
  }

  return updated === markdown
    ? null
    : `${GRAPH_DOC}: the workspace graph is out of date with the workspaces' package.json; run \`npm run graph\`.`;
}

/** A hand-drawn workspace graph: an import chain (`@sheavly/a  ←  …`) or a mermaid flowchart. */
const DRAWN_GRAPH = /@sheavly\/[a-z-]+\s+←|```mermaid\s+flowchart/;

/**
 * Markdown files (of `files`, relative to `root`) that draw the workspace graph by hand: it lives
 * once, generated, in the overview, and a copy would drift from it.
 */
export function copiedGraphProblems(params) {
  const { root, files } = params;

  return files
    .filter((file) => file.endsWith('.md') && !file.startsWith('workbook/'))
    .filter((file) => {
      const markdown = readFileSync(path.join(root, file), 'utf8');
      const outside =
        file === GRAPH_DOC ? (withGraph({ markdown, block: '' }) ?? markdown) : markdown;

      return DRAWN_GRAPH.test(outside);
    })
    .map(
      (file) =>
        `${file}: draws the workspace graph by hand. Link to it instead ([the graph](${path.posix.relative(path.posix.dirname(file), GRAPH_DOC)}#layers)); it is generated there from the workspaces.`,
    );
}

if (path.resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  const root = path.resolve(import.meta.dirname, '..');
  const file = path.join(root, GRAPH_DOC);
  const updated = withGraph({
    markdown: readFileSync(file, 'utf8'),
    block: graphBlock(readLayout({ root })),
  });

  if (updated === null) {
    console.error(graphProblem(root));
    process.exit(1);
  }

  writeFileSync(file, updated);
  console.log(`Wrote the workspace graph in ${GRAPH_DOC}.`);
}
